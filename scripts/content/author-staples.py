def r(slug, name, desc, minutes, ingredients, steps, tip, tags, motif, toppings,
      cuisine='和風', difficulty=1, vessel=None, base=None, equipment=None, colors=None, garnish=''):
    items = []
    for part in ingredients.split(';'):
        n, a = part.split('=', 1)
        items.append({'name':n, 'amount':a})
    instructions = [s.strip().rstrip('。')+'。' for s in steps.split('|')]
    assert 3 <= len(instructions) <= 6, (slug, len(instructions))
    assert len(items) >= 3 and len(items) == len({x['name'] for x in items}), slug
    assert len(tags.split(',')) in range(2,6), slug
    RECIPES.append({
        'id':'r-'+slug, 'name':name, 'description':desc.rstrip('。')+'。',
        'category':CATEGORY, 'cuisine':cuisine, 'difficulty':difficulty,
        'rarity':{1:'common',2:'rare',3:'special'}[difficulty],
        'minutes':minutes, 'servings':1, 'ingredients':items,
        'steps':instructions, 'tip':tip.rstrip('。')+'。', 'tags':tags.split(','),
        'equipment':equipment or ['包丁','まな板','鍋'],
        'reward':{1:20,2:40,3:70}[difficulty],
        'art':{'vessel':vessel or {'rice':'bowl','noodles':'deep-plate','soup':'bowl','breakfast':'plate','snack':'plate'}[CATEGORY],
               'base':base or {'rice':'rice','noodles':'noodles','soup':'soup','breakfast':'toast','snack':'cake'}[CATEGORY],
               'colors':colors or PALETTES[CATEGORY], 'garnish':garnish.split(',') if garnish else [],
               'motif':motif, 'toppings':toppings.split(',')}})

